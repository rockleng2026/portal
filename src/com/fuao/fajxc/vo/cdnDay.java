package com.fuao.fajxc.vo;

public class cdnDay {
	private int aDay;
	private int bDay;
	private int cDay;
	private int dDay;
	private int eDay;
	private int fDay;
	private int gDay;
	
	
	
	public cdnDay() {
		super();
	}
	public cdnDay(int aDay, int bDay, int cDay, int dDay, int eDay, int fDay,
			int gDay) {
		super();
		this.aDay = aDay;
		this.bDay = bDay;
		this.cDay = cDay;
		this.dDay = dDay;
		this.eDay = eDay;
		this.fDay = fDay;
		this.gDay = gDay;
	}
	public int getaDay() {
		return aDay;
	}
	public void setaDay(int aDay) {
		this.aDay = aDay;
	}
	public int getbDay() {
		return bDay;
	}
	public void setbDay(int bDay) {
		this.bDay = bDay;
	}
	public int getcDay() {
		return cDay;
	}
	public void setcDay(int cDay) {
		this.cDay = cDay;
	}
	public int getdDay() {
		return dDay;
	}
	public void setdDay(int dDay) {
		this.dDay = dDay;
	}
	public int geteDay() {
		return eDay;
	}
	public void seteDay(int eDay) {
		this.eDay = eDay;
	}
	public int getfDay() {
		return fDay;
	}
	public void setfDay(int fDay) {
		this.fDay = fDay;
	}
	public int getgDay() {
		return gDay;
	}
	public void setgDay(int gDay) {
		this.gDay = gDay;
	}

	
}
