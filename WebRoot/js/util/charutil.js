//功能：检测Value   是否在Lp..Hp之间   
function __In(Lp, Hp,Value)   
{   
	return	((Value<=Hp)&&(Value>=Lp));   
}

function __GetFirstChar(HZS)
{
	var ret = "";
	for(i=0;i<HZS.length;i++)
	{
		ret = ret + __GetPYChar(HZS.charAt(i));
	}
	return ret;
}

function __GetPYChar(HZ)
{
	var n = GetByteCode(HZ);
	if (n < 128)
	{
		return HZ;
	}
	else if (n<=0xD7F9)
	{
		if(n == 53456) return "H";  //行，在银行希望首字母是H
		if(__In(0xB0A1,0xB0C4,n))return'A';
		if(__In(0XB0C5,0XB2C0,n))return'B';
		if(__In(0xB2C1,0xB4ED,n))return'C';
		if(__In(0xB4EE,0xB6E9,n))return'D';
		if(__In(0xB6EA,0xB7A1,n))return'E';
		if(__In(0xB7A2,0xB8C0,n))return'F';
		if(__In(0xB8C1,0xB9FD,n))return'G';
		if(__In(0xB9FE,0xBBF6,n))return'H';
		if(__In(0xBBF7,0xBFA5,n))return'J';
		if(__In(0xBFA6,0xC0AB,n))return'K';
		if(__In(0xC0AC,0xC2E7,n))return'L';
		if(__In(0xC2E8,0xC4C2,n))return'M';
		if(__In(0xC4C3,0xC5B5,n))return'N';
		if(__In(0xC5B6,0xC5BD,n))return'O';
		if(__In(0xC5BE,0xC6D9,n))return'P';
		if(__In(0xC6D1,0xC8BA,n))return'Q';
		if(__In(0xC8BB,0xC8F5,n))return'R';
		if(__In(0xC8F6,0xCBF9,n))return'S';
		if(__In(0xCBFA,0xCDD9,n))return'T';
		if(__In(0xCDDA,0xCEF3,n))return'W';
		if(__In(0xCEF4,0xD1B8,n))return'X';
		if(__In(0xD1B9,0xD4D0,n))return'Y';
		if(__In(0xD4D1,0xD7F9,n))return'Z';
		return HZ;
	}
	else
	{
		var c1 = (n >> 8);
		var c2 = (n & 0xFF);
		var b1 = (c1&0x7F)-0x20 - 56;
		var b2 = (c2&0x7F)-0x20 - 1;
		if (b1>=0 && b1<=31 && b2>=0 && b2<=93)
		{
			return __SecondLevelFirstChars[b1].charAt(b2);
		}
		return  HZ;
	}
}